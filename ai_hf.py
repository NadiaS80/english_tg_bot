import requests
from myconfig import HF_API_URL, HUGGING_FACE_TOKEN

class AI_HF:

    API_URL = HF_API_URL
    HUGGING_FACE_TOKEN = HUGGING_FACE_TOKEN

    @staticmethod
    def example(text, level):
        """Generate an English example sentence for a given word and CEFR level.

        Args:
            text (str): The target English word.
            level (str): CEFR level (A1–C2).

        Returns:
            str | None: Generated example sentence, or None if request failed.
        """

        headers = {'Authorization': f'Bearer {AI_HF.HUGGING_FACE_TOKEN}'}
        main_prompt = f"""
Ты — нейромодель, создающая одно корректное примерное предложение на английском языке 
для изучаемого слова.  

Твоя задача:  
На основе полученного слова и уровня английского языка (например A1, A2, B1, B2, C1, C2) 
сформировать одно грамматически корректное, стилистически чистое и пунктуационно правильное 
предложение на английском языке.  

Требования:  
- предложение должно строго содержать переданное слово;  
- оно должно соответствовать заданному уровню английского языка:  
  простые конструкции для A1–A2, 
  более сложные — для B1–B2, 
  продвинутые и академические — для C1–C2;  
- длина предложения должна быть развернутой, примерно в диапазоне от 12 до 25 слов  
  (но всегда меньше 500 символов);  
- содержание предложения должно соответствовать тематике уровня и самому слову  
  (простые слова — бытовые примеры, сложные термины — научные или философские примеры);  
- предложение должно быть полностью на английском языке;  
- никаких объяснений, переводов, рассуждений, комментариев — только одно готовое предложение;  
- никаких кавычек, смайликов, эмоций, списка, форматирования, переносов строк, вопросов.  

Верни строго одно предложение, строго на английском языке.
"""

        negative_prompt = f"""
Ни при каких условиях не делай следующее:
- не пиши более одного предложения;  
- не добавляй перевод слова;  
- не объясняй слово и не рассуждай о нём;  
- не используй кавычки, списки, переносы строк или эмодзи;  
- не задавай встречные вопросы;  
- не начинай с фраз вроде 'Here is your sentence' или 'Sure';  
- не выходи за пределы 500 символов;  
- не меняй слово, которое должно быть включено в пример;  
- не используй слишком сложную грамматику, если уровень ниже B2;  
- не используй слишком простые конструкции, если уровень выше B1;  
- не придумывай ничего лишнего — только одно корректное предложение.  
"""
        payload = {
            'messages': [
                {
                    'role': 'user',
                    'content': (
                        f'Есть слово на английском языке: {text}. '
                        f'Есть уровень английского языка: {level} '
                        f'Выполни задания, описанные дальше. Позитивный промпт: {main_prompt}. Негативный промпт: {negative_prompt}. '
                        f'Верни строго одно предложение.'
                    )
                }
            ],
            'model': 'deepseek-ai/DeepSeek-V3-0324'
        }
        try:
            response = requests.post(AI_HF.API_URL, headers=headers, json=payload, timeout=20)

            data = response.json()
            if 'choices' in data and len(data['choices']) > 0:
                return data['choices'][0]['message']['content']
            return None
        except Exception as e:
            print("Ошибка API HF:", e)
            return None

    @staticmethod
    def corect_word(word):
        """Correct spelling mistakes in a given word or short phrase.

        Args:
            word (str): User-provided word or phrase.

        Returns:
            str: Corrected version of the input word or the original if uncertain.
        """

        headers = {'Authorization': f'Bearer {AI_HF.HUGGING_FACE_TOKEN}'}
        main_prompt = f"""
Ты — нейромодель, которая исправляет только орфографические ошибки и опечатки 
в словах или коротких фразах на русском или английском языке.

Твоя задача:
- Получить одно слово или короткую фразу от пользователя (на русском или английском).
- Если в написании есть опечатки или орфографические ошибки, вернуть ту же фразу с исправленным написанием.
- Если написание уже корректное, вернуть фразу БЕЗ ИЗМЕНЕНИЙ.

Строгие правила:
- НЕ переводишь слово и НЕ меняешь язык: если ввод был на русском — ответ на русском; если на английском — ответ на английском.
- НЕ меняешь смысл слова и НЕ подбираешь другой эквивалент — только поправляешь буквы, если они явно ошибочны.
- Сохраняешь тот же язык, ту же структуру и примерное количество слов (например: "put onn" → "put on", "яблоко" → "яблоко").
- Если ты не уверена, как исправить слово, верни его ТОЧНО в том виде, как оно было введено пользователем.
- Можешь исправлять опечатки, перепутанные буквы, пропущенные или лишние буквы, но НЕ обязан что-то исправлять, если уверенности нет.
- Не добавляй ничего лишнего — только исправленное слово или фразу.

Верни только одну строку: исправленное слово или фразу, без перевода, без пояснений.
"""
        negative_prompt = f"""
Ни при каких условиях не делай следующее:
- не переводи слово на другой язык;
- не подбирай синонимы или более "красивые" слова;
- не меняй смысл слова или фразы;
- не добавляй объяснений, комментариев, переводов или примеров;
- не возвращай несколько вариантов, только один;
- не используй кавычки, эмодзи, скобки, форматирование или переносы строк;
- не создавай предложения — возвращай только слово или фразу, которую исправляешь;
- если не уверена, что есть ошибка, верни исходный ввод без изменений.
"""
        payload = {
            'messages': [
                {
                    'role': 'user',
                    'content': (
                        f'Есть слово: {word}. '
                        f'Выполни задания, описанные дальше. Позитивный промпт: {main_prompt}. Негативный промпт: {negative_prompt}. '
                        f'Верни только одну строку: исправленное слово или фразу, без перевода, без пояснений, без встречных вопросов.'
                    )
                }
            ],
            'model': 'deepseek-ai/DeepSeek-V3-0324'
        }
        try:
            response = requests.post(AI_HF.API_URL, headers=headers, json=payload, timeout=20)

            data = response.json()
            if 'choices' in data and len(data['choices']) > 0:
                return data['choices'][0]['message']['content']
            return word
        except Exception as e:
            print("Ошибка API HF:", e)
            return word


    @staticmethod
    def estimate_level(user_dict):
        """Estimate a user's English proficiency level from their vocabulary list.

        Args:
            user_dict (str): String representation of the user's word pairs.

        Returns:
            str: Estimated CEFR level (A1–C2).
        """

        headers = {'Authorization': f'Bearer {AI_HF.HUGGING_FACE_TOKEN}'}
        main_prompt = f"""
Ты — модель, оценивающая примерный уровень владения английским языком пользователя
на основе списка его слов. Тебе передаются только английские слова.

Твоя задача:

1. Определи уровень каждого слова: A1, A2, B1, B2, C1 или C2.
2. Если слово встречается редко, имеет несколько возможных уровней или выглядит слишком сложным,
   относись к нему как к слову более низкого из подходящих уровней.
3. Подсчитай, сколько слов относится к каждому уровню.
4. Определи итоговый уровень пользователя:
   - если один уровень явно преобладает по количеству слов — выбери его;
   - если распределение смешанное — вычисли средний уровень;
   - если среднее попадает между двумя уровнями — выбери более низкий.
5. Верни строго один из вариантов: A1, A2, B1, B2, C1, C2.

Требования:
- Никаких комментариев, объяснений, описаний или дополнительного текста.
- Никаких кавычек, знаков препинания, смайликов, списков или пояснений.
- Ответ должен содержать только уровень(два символа: букву и цифру), например: B1.
"""
        negative_prompt = """
Ни при каких условиях не делай следующее:
- не объясняй выбор уровня;
- не описывай логику или ход рассуждений;
- не приводи список слов или их уровней;
- не добавляй текст «Ваш уровень:» или подобные фразы;
- не используй кавычки, переносы строк, смайлы или форматирование;
- не выводи несколько вариантов;
- не отвечай словами, только уровень;
- не придумывай уровни вне списка A1, A2, B1, B2, C1, C2.
Ответ должен состоять строго из двух символов.
"""
        payload = {
            'messages': [
                {
                    'role': 'user',
                    'content': (
                        f'Есть словарь слов пользователя: {user_dict}. '
                        f'Выполни задания, описанные дальше. Позитивный промпт: {main_prompt}. Негативный промпт: {negative_prompt}. '
                        f'Верни строго уровень английского языка (два символа: букву и цифру), , например: B1.'
                    )
                }
            ],
            'model': 'deepseek-ai/DeepSeek-V3-0324'
        }
        try:
            response = requests.post(AI_HF.API_URL, headers=headers, json=payload, timeout=20)

            data = response.json()
            if 'choices' in data and len(data['choices']) > 0:
                return data['choices'][0]['message']['content']
            return 'Ошибка! Уровень не определен.'
        except Exception as e:
            print("Ошибка API HF:", e)
            return 'Ошибка! Уровень не определен.'